import express from 'express';
import PDFDocument from 'pdfkit';
import { getOne, getAll } from '../db/database.js';

const router = express.Router();

// Generate PDF report for a patient
router.get('/pdf/:patientId', async (req, res) => {
  try {
    const { patientId } = req.params;

    // Fetch patient data
    const patient = await getOne('SELECT * FROM patients WHERE id = ?', [patientId]);

    if (!patient) {
      return res.status(404).json({ error: 'Patient not found' });
    }

    // Fetch activity sessions
    const sessions = await getAll(`
      SELECT game_id, COUNT(*) as count, AVG(score) as avgScore, MAX(created_at) as lastPlayed
      FROM activity_sessions
      WHERE patient_id = ?
      GROUP BY game_id
      ORDER BY count DESC
    `, [patientId]);

    // Fetch stats
    const stats = await getOne('SELECT * FROM stats WHERE patient_id = ?', [patientId]);

    // Fetch family members
    const familyMembers = await getAll('SELECT name, relation FROM family_members WHERE patient_id = ?', [patientId]);

    // Create PDF
    const doc = new PDFDocument({ margin: 50 });

    // Set response headers
    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', `attachment; filename=SMARA-Report-${patient.name.replace(/\s+/g, '-')}-${new Date().toISOString().split('T')[0]}.pdf`);

    // Pipe PDF to response
    doc.pipe(res);

    // Header
    doc.fontSize(24).text('SMARA Clinical Report', { align: 'center' });
    doc.moveDown();
    doc.fontSize(12).text(`Generated on: ${new Date().toLocaleDateString('en-IN', { year: 'numeric', month: 'long', day: 'numeric' })}`, { align: 'center' });
    doc.moveDown(2);

    // Patient Information
    doc.fontSize(16).text('Patient Information', { underline: true });
    doc.moveDown(0.5);
    doc.fontSize(12);
    doc.text(`Name: ${patient.name}`);
    doc.text(`Age: ${patient.age} years`);
    doc.text(`Preferred Language: ${patient.preferred_language}`);
    doc.text(`Secondary Language: ${patient.secondary_language}`);
    doc.moveDown(2);

    // Family Members
    if (familyMembers.length > 0) {
      doc.fontSize(16).text('Family Members', { underline: true });
      doc.moveDown(0.5);
      doc.fontSize(12);
      familyMembers.forEach(fm => {
        doc.text(`• ${fm.name} (${fm.relation})`);
      });
      doc.moveDown(2);
    }

    // Engagement Statistics
    if (stats) {
      doc.fontSize(16).text('Engagement Statistics', { underline: true });
      doc.moveDown(0.5);
      doc.fontSize(12);
      doc.text(`Total Activities Completed: ${stats.activities_completed}`);
      doc.text(`Memory Interactions: ${stats.memory_interactions}`);
      doc.text(`Total Engagement Time: ${stats.engagement_time} minutes`);
      doc.text(`Familiarity Score: ${stats.familiarity_score}%`);
      doc.moveDown(2);
    }

    // Activity Summary
    if (sessions.length > 0) {
      doc.fontSize(16).text('Activity Summary', { underline: true });
      doc.moveDown(0.5);
      doc.fontSize(12);

      const gameNames = {
        'who-is-this': 'Who is this?',
        'memory-match': 'Memory Match',
        'complete-song': 'Complete the Song',
        'familiar-place': 'Familiar Place',
        'memory-story': 'Memory Story',
        'guess-the-voice': 'Guess the Voice'
      };

      sessions.forEach(session => {
        const gameName = gameNames[session.game_id] || session.game_id;
        doc.text(`${gameName}:`);
        doc.text(`  Sessions Played: ${session.count}`, { indent: 20 });
        doc.text(`  Average Score: ${Math.round(session.avgScore || 0)}%`, { indent: 20 });
        doc.text(`  Last Played: ${new Date(session.lastPlayed).toLocaleDateString('en-IN')}`, { indent: 20 });
        doc.moveDown(0.5);
      });
      doc.moveDown();
    }

    // Clinical Notes Section
    doc.addPage();
    doc.fontSize(16).text('Clinical Notes', { underline: true });
    doc.moveDown(0.5);
    doc.fontSize(12);
    doc.text('Space for healthcare provider notes:', { continued: false });
    doc.moveDown(0.5);

    // Add lines for writing
    for (let i = 0; i < 15; i++) {
      doc.moveDown(0.8);
      doc.moveTo(50, doc.y).lineTo(550, doc.y).stroke();
    }

    // Footer
    doc.fontSize(10).text(
      'This report is generated by SMARA (Smart Memory and Recognition Aid) for cognitive engagement tracking.',
      50,
      doc.page.height - 100,
      { align: 'center', width: doc.page.width - 100 }
    );

    doc.text(
      'SMARA is designed for cognitive engagement support and does not replace professional medical advice.',
      50,
      doc.page.height - 70,
      { align: 'center', width: doc.page.width - 100 }
    );

    // Finalize PDF
    doc.end();
  } catch (error) {
    console.error('Error generating PDF report:', error);
    res.status(500).json({ error: 'Failed to generate PDF report' });
  }
});

export default router;
